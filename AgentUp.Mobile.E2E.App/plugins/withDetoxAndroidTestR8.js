const fs = require('node:fs');
const path = require('node:path');

const ANDROID_TEST_R8_RULES_FILE = 'proguard-rules-androidTest.pro';
const TEST_PROGUARD_FILES = `testProguardFiles "${ANDROID_TEST_R8_RULES_FILE}"`;
const MINIFY_IN_RELEASE_BUILDS = 'android.enableMinifyInReleaseBuilds';
const DETOX_APP_PROGUARD =
  'proguardFile "${rootProject.projectDir}/../node_modules/detox/android/detox/proguard-rules-app.pro"';

/**
 * Expo 58 minifies release APKs (`android.enableMinifyInReleaseBuilds=true`). Two Detox failures
 * follow.
 *
 * minifyReleaseAndroidTestWithR8 dies because RN 0.88 removed
 * NotThreadSafeBridgeIdleDebugListener (facebook/react-native#54559) and Detox 20.42 still
 * implements BridgeIdlingResource against it:
 *
 *   ERROR: R8: Missing class com.facebook.react.bridge.NotThreadSafeBridgeIdleDebugListener
 *
 * -keep cannot resurrect a class that is gone. -dontwarn on the androidTest APK is the R8 remedy.
 *
 * Once that APK builds, Detox never sends the instrumentation "ready" WebSocket: it integrates
 * with React Native through reflection, so a minified release hangs at launchApp unless Detox's
 * app keep rules are applied. This harness is never shipped, so minify goes off rather than
 * retaining RN in a disposable APK. The -dontwarn file and Detox's proguard-rules-app.pro stay
 * as the documented backup if minify is turned back on. Native launch already sets
 * detoxEnableSynchronization: 0, so the idle listener is not used.
 */
const ANDROID_TEST_R8_RULES = `# Generated by plugins/withDetoxAndroidTestR8.js. Do not edit: prebuild rewrites it.
# RN 0.88 removed NotThreadSafeBridgeIdleDebugListener; Detox 20.42 still references it.
-dontwarn com.facebook.react.bridge.NotThreadSafeBridgeIdleDebugListener
-keep class com.wix.detox.** { *; }
`;

function withDetoxAndroidTestR8(config) {
  const { withAppBuildGradle, withDangerousMod, withGradleProperties } = require('expo/config-plugins');

  config = withGradleProperties(config, mod => {
    disableMinifyInReleaseBuilds(mod.modResults);
    return mod;
  });

  config = withAppBuildGradle(config, mod => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error(`Expected app/build.gradle to be groovy, found ${mod.modResults.language}.`);
    }

    mod.modResults.contents = applyReleaseR8Rules(mod.modResults.contents);
    return mod;
  });

  return withDangerousMod(config, [
    'android',
    async modConfig => {
      writeAndroidTestR8Rules(modConfig.modRequest.platformProjectRoot);
      return modConfig;
    },
  ]);
}

function disableMinifyInReleaseBuilds(properties) {
  const existing = properties.find(
    item => item.type === 'property' && item.key === MINIFY_IN_RELEASE_BUILDS,
  );
  if (existing) {
    existing.value = 'false';
    return properties;
  }

  properties.push({ type: 'property', key: MINIFY_IN_RELEASE_BUILDS, value: 'false' });
  return properties;
}

function applyReleaseR8Rules(contents) {
  let next = contents;
  if (!next.includes(TEST_PROGUARD_FILES) || !next.includes(DETOX_APP_PROGUARD)) {
    const match = next.match(/^([ \t]*)proguardFiles .+$/m);
    if (!match) {
      throw new Error(
        'Expected app/build.gradle to declare proguardFiles on the release build type, and it did ' +
          'not. testProguardFiles and Detox\'s app keep rules have to sit next to that line.',
      );
    }

    const extras = [];
    if (!next.includes(TEST_PROGUARD_FILES)) extras.push(`${match[1]}${TEST_PROGUARD_FILES}`);
    if (!next.includes(DETOX_APP_PROGUARD)) extras.push(`${match[1]}${DETOX_APP_PROGUARD}`);
    next = next.replace(match[0], `${match[0]}\n${extras.join('\n')}`);
  }

  return next;
}

function writeAndroidTestR8Rules(platformProjectRoot) {
  const dest = path.join(platformProjectRoot, 'app', ANDROID_TEST_R8_RULES_FILE);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, ANDROID_TEST_R8_RULES, 'utf8');
  return dest;
}

module.exports = withDetoxAndroidTestR8;
module.exports.ANDROID_TEST_R8_RULES = ANDROID_TEST_R8_RULES;
module.exports.ANDROID_TEST_R8_RULES_FILE = ANDROID_TEST_R8_RULES_FILE;
module.exports.TEST_PROGUARD_FILES = TEST_PROGUARD_FILES;
module.exports.DETOX_APP_PROGUARD = DETOX_APP_PROGUARD;
module.exports.MINIFY_IN_RELEASE_BUILDS = MINIFY_IN_RELEASE_BUILDS;
module.exports.disableMinifyInReleaseBuilds = disableMinifyInReleaseBuilds;
module.exports.applyReleaseR8Rules = applyReleaseR8Rules;
module.exports.writeAndroidTestR8Rules = writeAndroidTestR8Rules;
